#!/usr/bin/env python3
"""Generate vim-copy-unicode.h from Python's unicodedata.

The C helper must classify text exactly like the reference rules it was
ported from: cell widths, str.isalnum(), str.isspace() and combining marks.
Run `make -C ~/.config/tmux unicode` after a Python Unicode update.
"""

from pathlib import Path
import sys
import unicodedata


HEADER = Path(__file__).with_name('vim-copy-unicode.h')
ZERO_WIDTH, WIDE, ALNUM, COMBINING, SPACE = 1, 2, 4, 8, 16


def properties(code):
    if 0xD800 <= code <= 0xDFFF:
        return 0  # Surrogates never survive UTF-8 decoding.
    char = chr(code)
    value = 0
    if unicodedata.combining(char) or unicodedata.category(char) in ('Mn', 'Me', 'Cf'):
        value |= ZERO_WIDTH
    elif unicodedata.east_asian_width(char) in ('W', 'F'):
        value |= WIDE
    if char.isalnum():
        value |= ALNUM
    if unicodedata.combining(char):
        value |= COMBINING
    if char.isspace():
        value |= SPACE
    return value


def generate():
    ascii = [properties(code) for code in range(0x80)]
    ranges, previous = [], None
    for code in range(0x80, sys.maxunicode + 1):
        value = properties(code)
        if value != previous:
            ranges.append((code, value))
            previous = value
    lines = [
        '/* Generated by vim_copy_unicode.py from Python\'s unicodedata (Unicode ' +
        unicodedata.unidata_version + '). Do not edit. */',
        f'enum {{ ZERO_WIDTH = {ZERO_WIDTH}, WIDE = {WIDE}, ALNUM = {ALNUM}, '
        f'COMBINING = {COMBINING}, SPACE = {SPACE} }};',
        'static const unsigned char ascii_properties[128] = {',
    ]
    for i in range(0, 128, 16):
        lines.append('    ' + ', '.join(str(value) for value in ascii[i:i + 16]) + ',')
    lines += ['};', '',
              '/* Each entry applies from its start to the next entry\'s start. */',
              'static const struct { unsigned start : 24, properties : 8; } unicode_ranges[] = {']
    entries = [f'{{0x{start:X}, {value}}}' for start, value in ranges]
    for i in range(0, len(entries), 8):
        lines.append('    ' + ', '.join(entries[i:i + 8]) + ',')
    lines.append('};')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    HEADER.write_text(generate())
