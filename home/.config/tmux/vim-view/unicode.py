#!/usr/bin/env python3
"""Generate unicode.h, the cell widths vim-view.c measures text with.

Widths follow Python's unicodedata: East Asian wide and full-width
characters take two cells; combining marks and format characters none.
Run `make unicode` here after a Python Unicode update.
"""

from pathlib import Path
import sys
import unicodedata


HEADER = Path(__file__).with_name('unicode.h')
ZERO_WIDTH, WIDE = 1, 2


def properties(code):
    if 0xD800 <= code <= 0xDFFF:
        return 0  # Surrogates never survive UTF-8 decoding.
    char = chr(code)
    if unicodedata.combining(char) or unicodedata.category(char) in ('Mn', 'Me', 'Cf'):
        return ZERO_WIDTH
    if unicodedata.east_asian_width(char) in ('W', 'F'):
        return WIDE
    return 0


def generate():
    ascii = [properties(code) for code in range(0x80)]
    ranges, previous = [], None
    for code in range(0x80, sys.maxunicode + 1):
        value = properties(code)
        if value != previous:
            ranges.append((code, value))
            previous = value
    lines = [
        '/* Generated by unicode.py from Python\'s unicodedata (Unicode ' +
        unicodedata.unidata_version + '). Do not edit. */',
        f'enum {{ ZERO_WIDTH = {ZERO_WIDTH}, WIDE = {WIDE} }};',
        'static const unsigned char ascii_properties[128] = {',
    ]
    for i in range(0, 128, 16):
        lines.append('    ' + ', '.join(str(value) for value in ascii[i:i + 16]) + ',')
    lines += ['};', '',
              '/* Each entry applies from its start to the next entry\'s start. */',
              'static const struct { unsigned start : 24, properties : 8; } unicode_ranges[] = {']
    entries = [f'{{0x{start:X}, {value}}}' for start, value in ranges]
    for i in range(0, len(entries), 8):
        lines.append('    ' + ', '.join(entries[i:i + 8]) + ',')
    lines.append('};')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    HEADER.write_text(generate())
